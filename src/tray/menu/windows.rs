//! Win32 popup menu adapter for tray context menus.
#![cfg(windows)]
#![allow(unsafe_code)]

use std::{ffi::OsStr, io, os::windows::ffi::OsStrExt};

use windows::{
    Win32::{
        Foundation::{HWND, LPARAM, POINT, WPARAM},
        Graphics::Dwm::DwmFlush,
        UI::WindowsAndMessaging::{
            AppendMenuW, CreatePopupMenu, DestroyMenu, HMENU, MENU_ITEM_FLAGS, MF_CHECKED,
            MF_DISABLED, MF_GRAYED, MF_STRING, MFT_RADIOCHECK, PostMessageW, SetForegroundWindow,
            TPM_RETURNCMD, TPM_RIGHTBUTTON, TrackPopupMenu, WM_NULL,
        },
    },
    core::PCWSTR,
};

use super::render::{TrayMenuRenderEntry, TrayMenuRenderItem, TrayMenuRenderPlan};

const MF_RADIOCHECK: MENU_ITEM_FLAGS = MENU_ITEM_FLAGS(MFT_RADIOCHECK.0);

#[derive(Debug)]
pub(crate) struct WindowsTrayMenu {
    handle: HMENU,
}

impl WindowsTrayMenu {
    pub(crate) fn from_plan(plan: &TrayMenuRenderPlan) -> io::Result<Self> {
        // SAFETY: CreatePopupMenu allocates a menu handle owned by the current process; the handle
        // is wrapped immediately and released exactly once by Drop.
        let handle = unsafe { CreatePopupMenu() }.map_err(|error| to_io_error(&error))?;
        let menu = Self { handle };
        menu.append_entries(menu.handle, &plan.entries)?;
        Ok(menu)
    }

    pub(crate) fn track_at(&self, owner: HWND, point: POINT) -> io::Result<Option<u32>> {
        // SAFETY: callers supply their owned root after a user menu gesture, matching the tray handoff.
        let _ = unsafe { SetForegroundWindow(owner) };
        // SAFETY: this menu remains owned throughout the synchronous nested loop; Windows retains neither borrowed handle.
        let command = unsafe {
            TrackPopupMenu(
                self.handle,
                TPM_RETURNCMD | TPM_RIGHTBUTTON,
                point.x,
                point.y,
                Some(0),
                owner,
                None,
            )
        };
        // SAFETY: this documented benign message completes popup task switching. A closed owner rejects it without a command effect.
        unsafe { PostMessageW(Some(owner), WM_NULL, WPARAM(0), LPARAM(0)) }
            .map_err(|error| to_io_error(&error))?;
        // SAFETY: wait for dismissal to reach DWM before a selected command can start capture or recording.
        unsafe { DwmFlush() }.map_err(|error| to_io_error(&error))?;
        Ok((command.0 != 0).then_some(command.0.cast_unsigned()))
    }

    fn append_entries(&self, parent: HMENU, entries: &[TrayMenuRenderEntry]) -> io::Result<()> {
        for entry in entries {
            match entry {
                TrayMenuRenderEntry::Item(item) => Self::append_item(parent, item)?,
                TrayMenuRenderEntry::Separator => Self::append_separator(parent)?,
                TrayMenuRenderEntry::Submenu {
                    label,
                    enabled,
                    entries,
                    ..
                } => self.append_submenu(parent, label, *enabled, entries)?,
            }
        }
        Ok(())
    }

    fn append_item(parent: HMENU, item: &TrayMenuRenderItem) -> io::Result<()> {
        let label = menu_label(item);
        let wide = wide_null(&label);
        let flags = menu_flags(item);
        let command_id = match item.command_id {
            Some(command_id) => usize::try_from(command_id).map_err(|_| {
                io::Error::other("tray menu command id exceeds platform command width")
            })?,
            None => 0,
        };
        // SAFETY: `parent` is owned by this menu tree; `wide` is NUL-terminated and lives through the
        // call; command ids are generated by the tray menu render plan and fit in usize.
        unsafe { AppendMenuW(parent, flags, command_id, PCWSTR(wide.as_ptr())) }
            .map_err(|error| to_io_error(&error))
    }

    fn append_separator(parent: HMENU) -> io::Result<()> {
        // SAFETY: `parent` is an owned popup menu handle in this menu tree.
        unsafe {
            AppendMenuW(
                parent,
                windows::Win32::UI::WindowsAndMessaging::MF_SEPARATOR,
                0,
                None,
            )
        }
        .map_err(|error| to_io_error(&error))
    }

    fn append_submenu(
        &self,
        parent: HMENU,
        label: &str,
        enabled: bool,
        entries: &[TrayMenuRenderEntry],
    ) -> io::Result<()> {
        // SAFETY: CreatePopupMenu allocates a child handle owned until it is attached to `parent`.
        let child = unsafe { CreatePopupMenu() }.map_err(|error| to_io_error(&error))?;
        if let Err(error) = self.append_entries(child, entries) {
            // SAFETY: the child was not attached after a failed recursive append.
            let _ = unsafe { DestroyMenu(child) };
            return Err(error);
        }
        let label = wide_null(label);
        let mut flags = MF_STRING | windows::Win32::UI::WindowsAndMessaging::MF_POPUP;
        if !enabled {
            flags |= MF_DISABLED | MF_GRAYED;
        }
        // HMENU is an opaque pointer in the generated bindings; MF_POPUP takes that handle in the
        // usize command slot, matching the Win32 ABI on supported Windows targets.
        let child_value = child.0 as usize;
        // SAFETY: attaching transfers child-menu ownership to `parent`; root Drop destroys the tree.
        let result = unsafe { AppendMenuW(parent, flags, child_value, PCWSTR(label.as_ptr())) };
        if let Err(error) = result {
            // SAFETY: failed attachment leaves the child independently owned by this function.
            let _ = unsafe { DestroyMenu(child) };
            return Err(to_io_error(&error));
        }
        Ok(())
    }
}

impl Drop for WindowsTrayMenu {
    fn drop(&mut self) {
        // SAFETY: the HMENU is owned by this RAII wrapper and is destroyed exactly once.
        let _ = unsafe { DestroyMenu(self.handle) };
    }
}

fn menu_flags(item: &TrayMenuRenderItem) -> MENU_ITEM_FLAGS {
    let mut flags = MF_STRING;
    if !item.enabled || item.command_id.is_none() {
        flags |= MF_DISABLED | MF_GRAYED;
    }
    if item.checked {
        flags |= MF_CHECKED;
    }
    if item.radio {
        flags |= MF_RADIOCHECK;
    }
    flags
}

fn menu_label(item: &TrayMenuRenderItem) -> String {
    match item.shortcut_label.as_deref() {
        Some(shortcut) if !shortcut.is_empty() => format!("{}\t{shortcut}", item.label),
        Some(_) | None => item.label.clone(),
    }
}

fn wide_null(value: &str) -> Vec<u16> {
    OsStr::new(value).encode_wide().chain([0]).collect()
}

fn to_io_error(error: &windows::core::Error) -> io::Error {
    io::Error::from_raw_os_error(error.code().0)
}
